use std::env;
use std::fs;
use std::path::Path;
use std::process::{self, Command};

const USAGE: &str = "Usage: nova-dev <new NAME|build|run|test|clean|info|doctor|package>";

fn main() {
    let mut args = env::args().skip(1);
    let Some(command) = args.next() else {
        eprintln!("{USAGE}");
        process::exit(2);
    };

    let result = match command.as_str() {
        "new" => match args.next() {
            Some(name) if args.next().is_none() => create_project(&name),
            _ => Err("Usage: nova-dev new <project-name>".to_owned()),
        },
        "build" => run_cargo("build"),
        "run" => run_cargo("run"),
        "test" => run_cargo("test"),
        "clean" => run_cargo("clean"),
        "info" => {
            println!("Project Nova developer tools");
            println!("nova-dev version: {}", env!("CARGO_PKG_VERSION"));
            println!("Nova syscall ABI: experimental definitions; no syscall entry point");
            println!("Nova UI: metadata preview only; no kernel window service");
            Ok(())
        }
        "doctor" => doctor(),
        "package" => Err(
            "Package creation is unavailable: the .npkg packager and signing workflow are not implemented."
                .to_owned(),
        ),
        _ => Err(format!("Unknown command '{command}'.\n{USAGE}")),
    };

    if let Err(error) = result {
        eprintln!("nova-dev: {error}");
        process::exit(1);
    }
}

fn create_project(name: &str) -> Result<(), String> {
    if !valid_project_name(name) {
        return Err(
            "Project names must start with an ASCII letter or digit and contain only ASCII letters, digits, '-' or '_'."
                .to_owned(),
        );
    }

    let root =
        env::current_dir().map_err(|error| format!("cannot read current directory: {error}"))?;
    let project = root.join(name);
    if project.exists() {
        return Err(format!(
            "{} already exists; refusing to overwrite it.",
            project.display()
        ));
    }

    fs::create_dir(&project)
        .map_err(|error| format!("cannot create {}: {error}", project.display()))?;
    let source = project.join("src");
    if let Err(error) = fs::create_dir(&source) {
        let _ = fs::remove_dir(&project);
        return Err(format!("cannot create source directory: {error}"));
    }

    let cargo_toml = format!(
        "[package]\nname = \"{}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\n",
        name.replace('-', "_")
    );
    let main_rs = format!(
        "fn main() {{\n    println!(\"Hello from {name}!\");\n    println!(\"This is a host Rust project. Nova user-mode execution is not available yet.\");\n}}\n"
    );

    if let Err(error) = fs::write(project.join("Cargo.toml"), cargo_toml)
        .and_then(|()| fs::write(source.join("main.rs"), main_rs))
        .and_then(|()| {
            fs::write(
                project.join("README.md"),
                format!(
                    "# {name}\n\nGenerated by `nova-dev new`. This template builds and runs as a host Rust application. It is not a Nova user-space executable.\n"
                ),
            )
        })
    {
        return Err(format!(
            "project directory was created but scaffold files could not be fully written: {error}"
        ));
    }

    println!("Created host Rust project at {}", project.display());
    println!("Next: cd {} && nova-dev run", project.display());
    Ok(())
}

fn valid_project_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 64
        && name
            .as_bytes()
            .first()
            .is_some_and(u8::is_ascii_alphanumeric)
        && name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
}

fn run_cargo(subcommand: &str) -> Result<(), String> {
    let directory =
        env::current_dir().map_err(|error| format!("cannot read current directory: {error}"))?;
    if !Path::new("Cargo.toml").is_file() {
        return Err(format!(
            "no Cargo.toml in {}. Run this command from a Rust project directory.",
            directory.display()
        ));
    }
    let status = Command::new("cargo")
        .arg(subcommand)
        .current_dir(&directory)
        .status()
        .map_err(|error| format!("could not start cargo: {error}"))?;
    if !status.success() {
        return Err(format!("cargo {subcommand} exited with {status}"));
    }
    Ok(())
}

fn doctor() -> Result<(), String> {
    let mut missing = false;
    for (name, args) in [
        ("cargo", vec!["--version"]),
        ("rustc", vec!["--version"]),
        ("qemu-system-x86_64", vec!["--version"]),
    ] {
        match Command::new(name).args(args).output() {
            Ok(output) if output.status.success() => {
                let version = String::from_utf8_lossy(&output.stdout);
                let version = version.lines().next().unwrap_or("available");
                println!("[ok] {name}: {version}");
            }
            _ => {
                println!("[missing] {name}");
                missing = true;
            }
        }
    }

    match Command::new("rustup")
        .args(["target", "list", "--installed"])
        .output()
    {
        Ok(output) if output.status.success() => {
            let installed = String::from_utf8_lossy(&output.stdout);
            if installed
                .lines()
                .any(|line| line.trim() == "x86_64-unknown-none")
            {
                println!("[ok] target: x86_64-unknown-none");
            } else {
                println!("[missing] Rust target x86_64-unknown-none");
                missing = true;
            }
        }
        _ => {
            println!("[unknown] rustup target status (rustup unavailable)");
            missing = true;
        }
    }

    if missing {
        println!("Some Nova development prerequisites are missing.");
    } else {
        println!("Basic Nova development prerequisites are available.");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::valid_project_name;

    #[test]
    fn project_name_validation_rejects_paths_and_shell_metacharacters() {
        for invalid in ["", ".", "..", "../escape", "a/b", "name space", "x;whoami"] {
            assert!(!valid_project_name(invalid), "accepted {invalid:?}");
        }
        assert!(valid_project_name("nova-demo"));
        assert!(valid_project_name("demo_2"));
    }
}
